  "在一个包含 8 类人群、260 人的公开数据集中，单个前额 IMU 与同一次行走中的下背部 IMU 相比，步频的典型误差（约 1.5 步/分）和大误差"
  "比例（约 9%）在总体上没有可检测的差异。大误差集中在步态不规则的片段，在两个位置同时出现。左右步长比低于 0.9 时，已有的单步"
  f"中位数算法可以偏离真实步频 5 步/分以上；改按跨步计算后，头部大误差比例降至 {_p('HE|C_peak_stride|big')}%，与自相关周期平均后"
