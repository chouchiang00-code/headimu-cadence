h1("讨论")
h2("头部与下背部")
p(
  "头部与下背部的比较是在同一个人的同一次行走上配对进行的，个体之间步态的差异在相减时抵消，所以 183 人足以把总体的大误差比例之差"
  "限定在 −2.0 至 2.3 个百分点之间。这个结论说的是总体：按单个人群看，区间宽度随人数变化，卒中组还不能排除 1.1 步/分的差异，"
  "帕金森病组头部的大误差比例是下背部的两倍，16 人的数据不能判断这是否偶然。两个位置的大误差大多出在同一批片段上，这些片段步律"
  "不规则，头部信号的规律性可以预测下背部是否出错；在没有大误差的片段中，头部在步频带的竖直加速度与下背部几乎相同。就这一数据而言，"
  "限制步频准确度的是步态，而不是传感器在头部还是在躯干。")
h2("为什么按跨步计算")
p(
  "已有的单传感器方法逐步检测、取单步间期的中位数，隐含的假设是左右步长相等。性质（1）给出了这一假设失效的条件，数据与它一致：参考"
  "中两种算法相差超过 5 步/分的片段几乎都满足左右步长比低于 0.9；换成跨步中位数后，这类片段近九成被修复，头部和下背部的大误差都"
  "减少四分之一以上，同一改动在另一种检测器上对头部同样有效。就大误差而言，跨步中位数、自相关和 AGS 没有可检测的差别，开发集交叉验证"
  "选出的两个方案也都以跨步统计为成分。因此本文的结论是统计单位的选择，不是某一组参数：在可能出现不对称步态的人群中，单个躯干或"
  "头部传感器的步频应按跨步计算。")
p(
  f"这一改动的价值在大误差上。典型误差的改善（头部 1.53 → {_p('HE|C_ags|med', nd=2)} 步/分）远小于帕金森病步频的最小可检测变化"
  "（15 步/分）⟦lang⟧，其中相当一部分还来自分辨率。每个大误差则至少为最小可检测变化的三分之一，AGS 使头部每 100 个片段少约 2 个"
  "这样的输出，减少的片段一半以上来自放射性脑白质病组和卒中组。")
h2("对头戴设备的意义")
p(
  "性质（2）把统计单位和硬件联系起来：单步中位数的分辨率与采样间隔成正比，降到 25 Hz 以下时量化步长本身就超过 5 步/分；跨步减半，"
  "自相关周期可以插值。仿真中，单步中位数在 20 Hz 时大误差增加 7 个百分点，跨步中位数增加 1 个百分点，AGS 不变。按常见 IMU 的数据"
  "手册，加速度计在 25 Hz 低功耗模式下的电流比正常模式低一个数量级以上，陀螺仪的工作电流约为加速度计的三倍 ⟦bmi270⟧；若仿真结果在"
  "真实低功耗硬件上成立，头戴设备可以只让加速度计以 20–25 Hz 运行来估计步频，代价是不识别转身时大误差或无输出增加约 2 个百分点。"
  "头部的步态信号比器件噪声高两个数量级以上，噪声和量化指标不需要特别要求。没有参考分段时，一半的无输出来自未校准的陀螺仪零偏，"
  "使用陀螺仪的设备需要静止校准。")
p(
  "按跨步计算不解决步态本身不规则的问题。SR ≥ 0.7 的片段中 AGS 的大误差不到 2%，这一范围覆盖了健康组几乎全部片段和帕金森病组的 "
  "85%，但只覆盖卒中组的 37% 和重度受损者的四成；在范围之外，头部和下背部都不可靠。SR 只需要设备自己的信号，可以随步频一起输出，"
  "供使用者判断结果是否可信。")
h2("与已有研究的比较")
p(
  "头部区域的已有研究集中在健康人：耳戴 EarGait 的跨步时间误差约 12 ms ⟦seifer⟧，太阳穴 IMU 在日常生活中的足跟着地 F1 约 93% "
  "⟦tasca⟧。在相同片段上不经调参运行 EarGait 检测器时，它在 4.9% 的片段中把步频算成两倍（⟪T:post⟫）。躯干传感器的研究中，偏瘫者"
  " ⟦trojaniello⟧ 和损害最重的人群 ⟦mico⟧ 最难处理，本文卒中组的结果与之一致，并显示同样的困难在头部和下背部同时出现。足部 IMU "
  "按跨步提取参数，在跑台上的病理步态中步频平均绝对误差为 0.7 步/分 ⟦laidig⟧，与头部 AGS 的中位误差"
  f"（{_p('HE|C_ags|med', nd=2)} 步/分）在同一量级；两者的统计量和行走条件不同。")
h2("局限性")
p(
  "参考为经验证的足部 IMU 算法，不是动作捕捉，卒中组约六分之一的片段参考可疑；转身边界来自下背部 IMU。传感器用绑带固定在前额，"
  "行走只有 6–10 m，参与者没有主动转头，眼镜的滑动和重新佩戴只做了仿真（⟪T:sims⟫），所以结论不能直接用于眼镜形态的设备和日常生活。"
  "采样率和传感器配置的结果来自对 100 Hz 实测信号的退化，真实低功耗模式下的滤波和时钟抖动没有建模。AGS 的设计只用了开发集，但此前"
  "测试集已用于头部与下背部的比较，作者看过其中大误差的分布，估计器的评估不是完全盲态的。每类人群只有 8–51 名测试参与者，"
  "DUO-GAIT 只有 16 名健康人且几乎没有大误差。")

